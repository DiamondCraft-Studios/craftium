#!/usr/bin/env python3
"""Builds src/main/resources/assets/craftium/bedrock_blocks.txt.gz, the Java <-> Bedrock block state table.

Input is GeyserMC's blocks.nbt (MIT, https://github.com/GeyserMC/mappings), which lists one Bedrock state for each Java
block state id of the Java release it was generated for, and that release's data-generator report
(`java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports`, file reports/blocks.json). The report gives
every id its block name and properties, so the output is keyed by name and properties instead of by id and keeps working
on neighbouring Minecraft versions.

Usage: generate_bedrock_blocks.py <blocks.nbt> <blocks.json> <output.gz>
Output lines: "@minecraft:block" starts a block, then one line per state: [*]<properties>TAB<bedrock name>TAB<bedrock states>.
A leading * marks the block's default state, an empty bedrock name means the Java name without its namespace, and each
bedrock state is key=<s|b|i>:value (string, byte, int) separated by semicolons.
"""
import gzip, json, struct, sys

def read_nbt(raw):
    b = raw; pos = [0]
    def u(fmt):
        v = struct.unpack_from(fmt, b, pos[0]); pos[0] += struct.calcsize(fmt); return v[0]
    def text():
        n = u('>H'); v = b[pos[0]:pos[0] + n].decode('utf8'); pos[0] += n; return v
    def payload(t):
        if t == 1: return ('b', u('>b'))
        if t == 2: return ('i', u('>h'))
        if t == 3: return ('i', u('>i'))
        if t == 4: return ('i', u('>q'))
        if t == 5: return ('f', u('>f'))
        if t == 6: return ('f', u('>d'))
        if t == 8: return ('s', text())
        if t == 9:
            item = u('>b'); n = u('>i'); return [payload(item) for _ in range(n)]
        if t == 10:
            out = {}
            while True:
                tag = u('>b')
                if tag == 0: return out
                key = text(); out[key] = payload(tag)
        raise ValueError('unsupported tag %d' % t)
    t = u('>b'); text(); return payload(t)

def main(nbt_path, report_path, out_path):
    mappings = read_nbt(gzip.decompress(open(nbt_path, 'rb').read()))['bedrock_mappings']
    report = json.load(open(report_path))
    states = {}
    for name, block in report.items():
        for state in block['states']: states[state['id']] = (name, state.get('properties', {}), state.get('default', False))
    if len(states) != len(mappings):
        sys.exit('The report has %d block states but the mappings have %d: they are from different releases' % (len(states), len(mappings)))
    lines = ['# Generated by scripts/generate_bedrock_blocks.py from GeyserMC/mappings blocks.nbt (MIT). See THIRD-PARTY-NOTICES.md.']
    last = None
    for i in range(len(mappings)):
        name, props, default = states[i]; entry = mappings[i]
        if name != last: lines.append('@' + name); last = name
        bedrock = entry['bedrock_identifier'][1] if 'bedrock_identifier' in entry else ''
        if bedrock == name.split(':', 1)[1]: bedrock = ''
        values = ';'.join('%s=%s:%s' % (k, v[0], v[1]) for k, v in sorted(entry.get('state', {}).items()))
        lines.append('%s%s\t%s\t%s' % ('*' if default else '', ','.join('%s=%s' % kv for kv in sorted(props.items())), bedrock, values))
    with gzip.GzipFile(out_path, 'wb', 9, mtime=0) as f: f.write(('\n'.join(lines) + '\n').encode('utf8'))
    print('%d states in %d blocks' % (len(mappings), len(report)))

if __name__ == '__main__': main(*sys.argv[1:4])
